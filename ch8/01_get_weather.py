# 引入套件
from openai import OpenAI
import os, json, requests
from dotenv import load_dotenv

# 讀取組態檔
load_dotenv()
MODEL_ID = os.getenv('MODEL_ID')

# 建立 OpenAI 用戶端
client = OpenAI()

## 定義天氣預報函數(get_weather)
def get_weather(latitude, longitude):
    response = requests.get(
        "https://api.open-meteo.com/v1/forecast" + \
        f"?latitude={latitude}&longitude={longitude}&current=temperature_2m" + \
        ",wind_speed_10m&hourly=temperature_2m,relative_humidity_2m,wind_speed_10m"
    )
    data = response.json()
    return data['current']['temperature_2m']

# 工具函數(get_weather)的定義
tools = [{
    "type": "function",
    "name": "get_weather",
    "description": "Get current temperature for provided coordinates in celsius.",
    "strict": True,
    "parameters": {
        "type": "object",
        "properties": {
            "latitude": {"type": "number"},
            "longitude": {"type": "number"}
        },
        "required": ["latitude", "longitude"],
        "additionalProperties": False
    }
}]

# 提示
input_list = [{"role": "user", "content": "What is the weather in Taipei today?"}]

# 呼叫 OpenAI API
response = client.responses.create(
    model=MODEL_ID, # 模型
    tools=tools,        # 指定函數
    input=input_list,   # 提示
)

# 顯示執行結果
print('API執行結果：\n' + response.model_dump_json(indent=2))

# 根據回應內的呼叫函數的名稱及參數值，執行函數
def call_function(function_name, args):
    return globals()[function_name](**args)

# 呼叫 call_function，並整理執行結果
input_messages = []
for tool_call in response.output:
    if tool_call.type != "function_call":
        continue

    # 解析OpenAI API的回應
    name = tool_call.name
    args = json.loads(tool_call.arguments)

    # 根據解析結果呼叫函數
    result = call_function(name, args)
    input_messages.append({
        "type": "function_call_output",
        "call_id": tool_call.call_id,
        "output": json.dumps(result)
    })
print('解析API回應：')
print(input_messages)    

# 請LLM再美化內容
prompt = "repsonse 'it's hot if the weather generated by tool is higher than 25°C else it's cool."
response2 = client.responses.create(
    model=MODEL_ID,
    previous_response_id=response.id,
    instructions=prompt,
    input=input_messages,
    tools=tools,
)
print('最後結果：\n' + response2.output_text)



