"""Generates a standalone, reproducible Matplotlib Python script from a model.

This is a pure code generator: it reads a
:class:`~matplotlib_designer.models.figure_model.FigureModel` and emits
Python source text. It does not touch any live Matplotlib objects, so the
generated script is fully independent of the running application and will
reproduce the figure exactly when executed on its own.
"""
from __future__ import annotations

from pathlib import Path
from typing import List, Union

from ..models.annotation_model import AnnotationModel
from ..models.axes_model import AxesModel
from ..models.figure_model import FigureModel
from ..models.plot_model import PlotModel
from ..models.shape_model import ShapeModel
from ..models.text_model import TextModel


def export_script(figure: FigureModel, path: Union[str, Path]) -> None:
    """Write a standalone ``.py`` script that reproduces ``figure``.

    Args:
        figure: The document to generate code for.
        path: Destination ``.py`` file path.
    """
    Path(path).write_text(generate_script(figure), encoding="utf-8")


def generate_script(figure: FigureModel) -> str:
    """Render ``figure`` to Matplotlib Python source code.

    Args:
        figure: The document to generate code for.

    Returns:
        The full script as a single string, ready to save or ``exec``.
    """
    lines: List[str] = [
        '"""Auto-generated by Matplotlib Designer. Reproduces the designed figure."""',
        "import matplotlib.pyplot as plt",
        "from matplotlib.patches import Rectangle, Ellipse",
        "from matplotlib.lines import Line2D",
        "",
        f"fig = plt.figure(figsize=({figure.width_in}, {figure.height_in}), dpi={figure.dpi}, "
        f"facecolor={figure.facecolor!r})",
    ]
    if figure.suptitle:
        lines.append(f"fig.suptitle({figure.suptitle!r})")
    lines.append("")

    for index, axes in enumerate(figure.axes, start=1):
        lines.extend(_render_axes(axes, index))

    if figure.layout == "tight":
        lines.append("fig.tight_layout()")
    lines.append("")
    lines.append("if __name__ == '__main__':")
    lines.append("    plt.show()")
    return "\n".join(lines)


def _render_axes(axes: AxesModel, index: int) -> List[str]:
    var = f"ax{index}"
    projection = None if axes.projection == "rectilinear" else axes.projection
    proj_kw = f", projection={projection!r}" if projection else ""
    lines = [
        f"{var} = fig.add_axes({list(axes.position)}{proj_kw})",
        f"{var}.set_facecolor({axes.facecolor!r})",
        f"{var}.grid({axes.show_grid})",
    ]
    if axes.title.content:
        lines.append(
            f"{var}.set_title({axes.title.content!r}, fontsize={axes.title.font_size}, "
            f"fontweight={axes.title.font_weight!r}, color={axes.title.color!r})"
        )
    if axes.xlabel.content:
        lines.append(f"{var}.set_xlabel({axes.xlabel.content!r}, fontsize={axes.xlabel.font_size})")
    if axes.ylabel.content:
        lines.append(f"{var}.set_ylabel({axes.ylabel.content!r}, fontsize={axes.ylabel.font_size})")

    for plot in axes.plots:
        lines.extend(_render_plot(var, plot))
    if axes.show_legend and any(p.label for p in axes.plots):
        lines.append(f"{var}.legend(loc={axes.legend_loc!r})")
    for shape in axes.shapes:
        lines.extend(_render_shape(var, shape))
    for text in axes.texts:
        lines.extend(_render_text(var, text))
    for annotation in axes.annotations:
        lines.extend(_render_annotation(var, annotation))
    lines.append("")
    return lines


def _render_plot(var: str, plot: PlotModel) -> List[str]:
    kw = f"color={plot.color!r}, label={plot.label!r}" if plot.label else f"color={plot.color!r}"
    kind = plot.kind
    if kind == "line":
        return [f"{var}.plot({plot.x}, {plot.y}, linestyle={plot.line_style!r}, "
                f"linewidth={plot.line_width}, marker={plot.marker!r}, markersize={plot.marker_size}, {kw})"]
    if kind == "scatter":
        return [f"{var}.scatter({plot.x}, {plot.y}, s={plot.marker_size ** 1.6}, {kw})"]
    if kind == "bar":
        return [f"{var}.bar({plot.x}, {plot.y}, {kw})"]
    if kind == "barh":
        return [f"{var}.barh({plot.x}, {plot.y}, {kw})"]
    if kind == "hist":
        return [f"{var}.hist({plot.y or plot.x}, {kw})"]
    if kind == "pie":
        return [f"{var}.pie({plot.y or plot.x})"]
    if kind == "box":
        return [f"{var}.boxplot({plot.y or plot.x})"]
    if kind == "violin":
        return [f"{var}.violinplot({plot.y or plot.x})"]
    if kind == "stem":
        return [f"{var}.stem({plot.x}, {plot.y})"]
    if kind == "step":
        return [f"{var}.step({plot.x}, {plot.y}, {kw})"]
    if kind == "heatmap" and plot.z is not None:
        return [f"{var}.imshow({plot.z}, cmap={plot.colormap!r}, aspect='auto')"]
    if kind == "contour" and plot.z is not None:
        return [f"{var}.contour({plot.z}, cmap={plot.colormap!r})"]
    if kind == "image" and plot.z is not None:
        return [f"{var}.imshow({plot.z}, cmap={plot.colormap!r})"]
    if kind == "errorbar":
        return [f"{var}.errorbar({plot.x}, {plot.y}, yerr={plot.yerr}, {kw})"]
    if kind == "stack":
        return [f"{var}.stackplot({plot.x}, {plot.y}, colors=[{plot.color!r}])"]
    if kind == "area":
        return [f"{var}.fill_between({plot.x}, {plot.y}, color={plot.color!r}, alpha=0.5, label={plot.label!r})"]
    return []


def _render_shape(var: str, shape: ShapeModel) -> List[str]:
    common = (f"edgecolor={shape.edge_color!r}, facecolor={shape.face_color!r}, "
              f"linewidth={shape.line_width}, linestyle={shape.line_style!r}, "
              f"transform={var}.transAxes, clip_on=False")
    if shape.kind == "rectangle":
        return [f"{var}.add_patch(Rectangle(({shape.x}, {shape.y}), {shape.width}, {shape.height}, "
                f"angle={shape.rotation}, {common}))"]
    if shape.kind in ("ellipse", "circle"):
        cx, cy = shape.x + shape.width / 2, shape.y + shape.height / 2
        return [f"{var}.add_patch(Ellipse(({cx}, {cy}), {shape.width}, {shape.height}, "
                f"angle={shape.rotation}, {common}))"]
    if shape.points:
        xs = [p[0] for p in shape.points]
        ys = [p[1] for p in shape.points]
        return [f"{var}.add_line(Line2D({xs}, {ys}, color={shape.edge_color!r}, "
                f"linewidth={shape.line_width}, linestyle={shape.line_style!r}, transform={var}.transAxes))"]
    return []


def _render_text(var: str, text: TextModel) -> List[str]:
    bbox = "None" if text.background == "none" else f"dict(facecolor={text.background!r}, edgecolor='none')"
    return [
        f"{var}.text({text.x}, {text.y}, {text.content!r}, transform={var}.transAxes, "
        f"ha={text.ha!r}, va={text.va!r}, rotation={text.rotation}, color={text.color!r}, "
        f"fontsize={text.font_size}, fontweight={text.font_weight!r}, fontstyle={text.font_style!r}, "
        f"bbox={bbox})"
    ]


def _render_annotation(var: str, annotation: AnnotationModel) -> List[str]:
    arrowprops = "None" if not annotation.arrow_style else (
        f"dict(arrowstyle={annotation.arrow_style!r}, color={annotation.edge_color!r})"
    )
    bbox = "None" if annotation.box_style == "none" else (
        f"dict(boxstyle={annotation.box_style!r}, fc={annotation.face_color!r}, ec={annotation.edge_color!r})"
    )
    return [
        f"{var}.annotate({annotation.text!r}, xy=({annotation.x}, {annotation.y}), "
        f"xytext=({annotation.xtext}, {annotation.ytext}), xycoords='axes fraction', "
        f"textcoords='axes fraction', arrowprops={arrowprops}, bbox={bbox}, fontsize={annotation.font_size})"
    ]
